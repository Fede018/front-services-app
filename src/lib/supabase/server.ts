import { createServerClient } from "@supabase/ssr";
import { cookies } from "next/headers";
import type { Database } from "@/types/database";
import { getSupabaseEnv } from "./env";

/** Cliente para Server Components, Server Actions y Route Handlers. Usa la sesion del usuario (RLS aplica). */
export async function createClient() {
  const cookieStore = await cookies();
  const { url, anonKey } = getSupabaseEnv();

  return createServerClient<Database>(url, anonKey, {
    cookies: {
      getAll() {
        return cookieStore.getAll();
      },
      setAll(cookiesToSet) {
        try {
          for (const { name, value, options } of cookiesToSet) cookieStore.set(name, value, options);
        } catch {
          // Se llama desde un Server Component: no se pueden escribir cookies. Lo resuelve el refresco de sesion (SPEC 03).
        }
      },
    },
  });
}
